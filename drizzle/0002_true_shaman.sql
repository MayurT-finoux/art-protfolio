CREATE TABLE "projects" (
	"id" serial PRIMARY KEY NOT NULL,
	"slug" text NOT NULL,
	"title" text NOT NULL,
	"kind" text DEFAULT '' NOT NULL,
	"year" text DEFAULT '' NOT NULL,
	"client" text DEFAULT '' NOT NULL,
	"role" text DEFAULT '' NOT NULL,
	"tools" text DEFAULT '' NOT NULL,
	"teaser" text DEFAULT '' NOT NULL,
	"cover_url" text DEFAULT '' NOT NULL,
	"cover_is_video" boolean DEFAULT false NOT NULL,
	"story" jsonb DEFAULT '[]'::jsonb NOT NULL,
	"process" jsonb DEFAULT '[]'::jsonb NOT NULL,
	"finals" jsonb DEFAULT '[]'::jsonb NOT NULL,
	"youtube_id" text,
	"behance_url" text,
	"behance_text" text DEFAULT '' NOT NULL,
	"position" integer DEFAULT 0 NOT NULL,
	"status" text DEFAULT 'draft' NOT NULL,
	"seo_title" text,
	"seo_description" text,
	"created_at" timestamp with time zone DEFAULT now() NOT NULL,
	"updated_at" timestamp with time zone DEFAULT now() NOT NULL,
	CONSTRAINT "projects_slug_unique" UNIQUE("slug")
);
